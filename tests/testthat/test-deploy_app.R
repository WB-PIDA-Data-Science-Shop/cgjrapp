# Deployment to Posit Connect: the generated entry file, which files are
# bundled (the Official Use Only guidance PDF and private notes must never
# be), and the deploy_app() paths. rsconnect::deployApp() is mocked: no
# network, nothing is published.

# A minimal app directory with the files that matter for bundling.
local_app_dir <- function(env = parent.frame()) {
  dir <- withr::local_tempdir(.local_envir = env)
  files <- c("DESCRIPTION", "R/run_cgjrapp.R", "inst/www/styles.css",
             "inst/docs/guidance_passages.rds", "inst/docs/guidance_passages_embeddings.rds",
             "inst/docs/Guidance_ institutional review_final.pdf", "inst/docs/notes.txt")
  for (f in file.path(dir, files)) {
    dir.create(dirname(f), recursive = TRUE, showWarnings = FALSE)
    writeLines("x", f)
  }
  dir
}

test_that("write_deploy_entrypoint() loads the bundle's source and calls run_cgjrapp()", {
  path <- withr::local_tempfile(fileext = ".R")
  write_deploy_entrypoint(path)
  lines <- readLines(path)
  expect_match(lines[[1]], "Generated by deploy_app", fixed = TRUE)
  expect_true(any(grepl("pkgload::load_all(export_all = FALSE, helpers = FALSE, attach_testthat = FALSE)",
                        lines, fixed = TRUE)))
  expect_identical(lines[[length(lines)]], "cgjrapp::run_cgjrapp()")
})

test_that("write_deploy_entrypoint() bakes its arguments into the call", {
  path <- withr::local_tempfile(fileext = ".R")
  write_deploy_entrypoint(path, options = list(port = 1L), uiPattern = "/")
  call <- str2lang(paste(readLines(path)[-(1:3)], collapse = "\n"))
  expect_identical(call[[1]], quote(cgjrapp::run_cgjrapp))
  expect_identical(eval(call$options), list(port = 1L))
  expect_identical(call$uiPattern, "/")
})

test_that(".bundle_files() keeps only the allowed guidance files from inst/docs", {
  files <- .bundle_files(local_app_dir())
  expect_true(all(c("inst/docs/guidance_passages.rds",
                    "inst/docs/guidance_passages_embeddings.rds") %in% files))
  expect_false(any(grepl("\\.pdf$|notes\\.txt$", files)))
  expect_true(all(c("DESCRIPTION", "R/run_cgjrapp.R", "inst/www/styles.css") %in% files))
})

test_that(".check_bundle() refuses private files and accepts a clean bundle", {
  ok <- c("DESCRIPTION", "R/a.R", "inst/docs/guidance_passages.rds")
  expect_identical(.check_bundle(ok), ok)
  for (bad in c(".Renviron", "R/.Renviron", ".plans/plan.md", "copilot_logs/LOG_mai-integration.md",
                "data-raw/Guidance.docx", "inst/docs/Guidance.pdf", "prompts/PLAN.md")) {
    expect_error(.check_bundle(c(ok, bad)), bad, fixed = TRUE)
  }
})

test_that("the repository's own bundle holds no private files", {
  # the source tree, under devtools::test(); not there in R CMD check
  root <- testthat::test_path("..", "..")
  skip_if_not(file.exists(file.path(root, ".rscignore")), "not run from the source tree")
  files <- .bundle_files(root)
  expect_identical(.check_bundle(files), files)
  expect_false(any(startsWith(files, "renv/") | startsWith(files, "tests/") | startsWith(files, "man/")))
})

test_that("deploy_app() needs the slot's GUID unless it creates new content", {
  dir <- local_app_dir()
  called <- FALSE
  local_mocked_bindings(deployApp = function(...) called <<- TRUE, .package = "rsconnect")
  withr::local_envvar(cgjrapp_dev_guid = NA, cgjrapp_prod_guid = "g-prod")
  expect_error(deploy_app(type = "dev", app_dir = dir), "cgjrapp_dev_guid")
  expect_error(deploy_app(type = "prod", new = TRUE, app_dir = dir), "already set")
  expect_false(called)
})

test_that("deploy_app() publishes the checked files to the slot's GUID", {
  dir <- local_app_dir()
  seen <- NULL
  local_mocked_bindings(deployApp = function(...) { seen <<- list(...); invisible(TRUE) },
                        .package = "rsconnect")
  withr::local_envvar(cgjrapp_dev_guid = "g-dev")
  deploy_app(type = "dev", app_dir = dir)
  expect_identical(seen$appId, "g-dev")
  expect_identical(seen$server, "datanalytics-int.worldbank.org")
  expect_identical(seen$appPrimaryDoc, "inst/app/cgjrapp_app.R")
  expect_true("inst/app/cgjrapp_app.R" %in% seen$appFiles)
  expect_false(any(grepl("\\.pdf$", seen$appFiles)))
  expect_true(file.exists(file.path(dir, "inst/app/cgjrapp_app.R")))
})

test_that("deploy_app(new = TRUE) creates the content and reports its GUID", {
  dir <- local_app_dir()
  seen <- NULL
  local_mocked_bindings(deployApp = function(...) { seen <<- list(...); invisible(TRUE) },
                        .package = "rsconnect")
  local_mocked_bindings(deployments = function(...) data.frame(
    name = c("cgjrapp-dev", "other"),
    url = c("https://datanalytics-int.worldbank.org/content/0a1b2c3d-1111-2222-3333-444455556666/",
            "https://datanalytics-int.worldbank.org/content/ffffffff-1111-2222-3333-444455556666/")),
    .package = "rsconnect")
  withr::local_envvar(cgjrapp_dev_guid = NA)
  expect_message(deploy_app(type = "dev", new = TRUE, app_dir = dir),
                 "cgjrapp_dev_guid=0a1b2c3d-1111-2222-3333-444455556666", fixed = TRUE)
  expect_null(seen$appId)
  expect_identical(seen$appName, "cgjrapp-dev")
})
