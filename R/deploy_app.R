# deploy_app.R - publishing cgjrapp to Posit Connect, the same way
# cliarappak does: a generated entry file that loads the bundle's source,
# a GUID per slot (dev / prod) from the developer's .Renviron, and
# rsconnect::deployApp(). Unlike cliarappak, the files to bundle are listed
# and checked here: inst/docs/ holds the Official Use Only guidance note,
# and .rscignore cannot exclude files by pattern.

# The files of inst/docs/ that may be bundled: the guidance passages and
# their embeddings, built by data-raw/. Never the note itself.
.BUNDLE_DOCS <- c("inst/docs/guidance_passages.rds", "inst/docs/guidance_passages_embeddings.rds")

# Paths that must never be bundled (a file, or a directory with a trailing
# slash). .rscignore excludes them; .check_bundle() makes sure it did.
.BUNDLE_FORBIDDEN <- c(".Renviron", ".plans/", "copilot_logs/", "data-raw/", "prompts/")

#' Generate the Posit Connect entry file
#'
#' Writes the file Posit Connect runs on every launch, restart and
#' scale-out of the deployed content. Connect does not install the bundle's
#' own package, so the file loads it from the bundle's source with
#' [pkgload::load_all()]; `R/_disable_autoload.R` stops shiny from also
#' sourcing `R/` itself. Arguments of [run_cgjrapp()] are written into the
#' file, so they hold for every restart, not only the first launch.
#'
#' @param path Where to write the entry file.
#' @param ... Named arguments for the generated `run_cgjrapp()` call. Each
#'   is written with [deparse()], so values must be literals (NULL, strings,
#'   numbers, simple lists).
#' @return `path`, invisibly.
#' @noRd
write_deploy_entrypoint <- function(path, ...) {
  args <- list(...)
  arg_src <- vapply(names(args), function(nm) {
    paste0(nm, " = ", paste(deparse(args[[nm]]), collapse = "\n"))
  }, character(1))
  lines <- c(
    "# Generated by deploy_app() - do not hand-edit; not tracked in git.",
    "pkgload::load_all(export_all = FALSE, helpers = FALSE, attach_testthat = FALSE)",
    "",
    paste0("cgjrapp::run_cgjrapp(", paste(arg_src, collapse = ", "), ")")
  )
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, path)
  invisible(path)
}

# The files rsconnect would bundle from `app_dir` (.rscignore applied), less
# every file in inst/docs/ but the guidance passages and their embeddings.
.bundle_files <- function(app_dir) {
  files <- rsconnect::listDeploymentFiles(app_dir)
  files[!startsWith(files, "inst/docs/") | files %in% .BUNDLE_DOCS]
}

# Stops, naming them, if any files that must stay private are in `files`.
# Returns `files` otherwise.
.check_bundle <- function(files) {
  is_dir <- endsWith(.BUNDLE_FORBIDDEN, "/")
  bad <- files[basename(files) %in% .BUNDLE_FORBIDDEN[!is_dir] |
               vapply(files, function(f) any(startsWith(f, .BUNDLE_FORBIDDEN[is_dir])), logical(1)) |
               (startsWith(files, "inst/docs/") & !files %in% .BUNDLE_DOCS)]
  if (length(bad)) {
    stop("These files must not be deployed: ", paste(bad, collapse = ", "),
         ". Add them to .rscignore.", call. = FALSE)
  }
  files
}

#' Deploy cgjrapp to Posit Connect
#'
#' Regenerates the entry file (`inst/app/cgjrapp_app.R`), lists the files to
#' bundle and checks that none must stay private, then publishes them with
#' [rsconnect::deployApp()].
#'
#' Only two files of `inst/docs/` are bundled: `guidance_passages.rds` and
#' its embeddings. The guidance note itself (a PDF, Official Use Only) and
#' anything else there never is. Private notes (`.plans/`, `copilot_logs/`),
#' `data-raw/`, `prompts/` and any `.Renviron` are excluded by `.rscignore`,
#' and the deploy stops if one gets through.
#'
#' The app's settings are not deployed from here: set the `CGJR_*`
#' environment variables in the content's Vars panel on Connect (see the
#' README). Your local values (a desktop mAI token, a local Python project)
#' do not apply there.
#'
#' @param type `"dev"` or `"prod"`: the Connect content to deploy to, whose
#'   GUID is read from the environment variable `cgjrapp_dev_guid` or
#'   `cgjrapp_prod_guid`. Set it in your `.Renviron` (never committed); the
#'   GUID is the "Content GUID" in the app's Info panel on Connect.
#' @param new `TRUE` to create the content on Connect - once per slot, when
#'   its GUID variable is not set yet. The new GUID is printed, to be added
#'   to your `.Renviron`.
#' @param server A Posit Connect server registered with rsconnect
#'   ([rsconnect::servers()]), with an account for you
#'   ([rsconnect::accounts()]; add one with [rsconnect::connectApiUser()]).
#' @param forceUpdate Passed to [rsconnect::deployApp()]: no confirmation
#'   prompt on redeploys.
#' @param app_dir The package's source directory.
#' @param ... Named arguments written into the entry file's `run_cgjrapp()`
#'   call (passed on to [shiny::shinyApp()]).
#' @return `TRUE`, invisibly. Stops if Connect fails to build or start the
#'   content (after printing a new slot's GUID: the content was created).
#' @examples
#' \dontrun{
#' # First deploy of a slot: creates the content and prints its GUID
#' deploy_app(type = "dev", new = TRUE)
#'
#' # Every later deploy (cgjrapp_dev_guid set in .Renviron)
#' deploy_app(type = "dev")
#' deploy_app(type = "prod")
#' }
#' @export
deploy_app <- function(type = c("dev", "prod"), new = FALSE,
                       server = "datanalytics-int.worldbank.org", forceUpdate = TRUE,
                       app_dir = ".", ...) {
  type <- match.arg(type)
  guid_var <- paste0("cgjrapp_", type, "_guid")
  guid <- Sys.getenv(guid_var)
  if (new && nzchar(guid)) {
    stop(guid_var, " is already set: the ", type, " content exists. ",
         "Deploy to it with deploy_app(type = \"", type, "\").", call. = FALSE)
  }
  if (!new && !nzchar(guid)) {
    stop("Environment variable '", guid_var, "' is not set. Set it in your .Renviron ",
         "(the app's Content GUID on Connect), or create the content with ",
         "deploy_app(type = \"", type, "\", new = TRUE).", call. = FALSE)
  }

  primary_doc <- "inst/app/cgjrapp_app.R"
  write_deploy_entrypoint(file.path(app_dir, primary_doc), ...)
  files <- .check_bundle(.bundle_files(app_dir))
  if (!"inst/docs/guidance_passages.rds" %in% files) {
    warning("inst/docs/guidance_passages.rds is not bundled: the deployed app can use only ",
            "the stand-in guidance. Build it with data-raw/guidance_passages.R.", call. = FALSE)
  }

  app_name <- if (type == "prod") "cgjrapp" else "cgjrapp-dev"
  out <- rsconnect::deployApp(
    appDir        = app_dir,
    appFiles      = files,
    appPrimaryDoc = primary_doc,
    appId         = if (!new) guid,
    appName       = if (new) app_name,
    appTitle      = app_name,
    server        = server,
    forceUpdate   = forceUpdate
  )
  # The content exists once created, even if Connect then fails to build it:
  # report its GUID either way, so a retry redeploys rather than duplicates.
  if (new) .report_new_guid(file.path(app_dir, primary_doc), server, app_name, guid_var)
  if (!isTRUE(out)) {
    stop("Deployment to ", type, " failed: see the Connect log above. Fix the cause, then ",
         "redeploy with deploy_app(type = \"", type, "\").", call. = FALSE)
  }
  invisible(out)
}

# After a first deploy: the new content's GUID, from rsconnect's deployment
# record, as the line to add to .Renviron. rsconnect files the record of a
# single-file deploy under that file (inst/app/rsconnect/documents/...), so
# `record_path` is the entry file, not the app directory.
.report_new_guid <- function(record_path, server, app_name, guid_var) {
  d <- rsconnect::deployments(record_path, serverFilter = server)
  url <- d$url[d$name == app_name]
  guid <- regmatches(url, regexpr("[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}", url))
  if (length(guid) == 1L) {
    message("Created. Add this line to your .Renviron, then restart R:\n  ",
            guid_var, "=", guid)
  } else {
    message("Created. Copy the Content GUID from the app's Info panel on Connect into ",
            "your .Renviron as ", guid_var, ".")
  }
}
